"""Regenerate the optional media worker's complete wheel hash lock.

Run with uv installed: python tools/lock_media_requirements.py
The Python 3.12 universal resolution covers the worker's Linux image platforms.
Review version changes and run tools/check_media_worker.py on Linux after rebuilding.
The Docker build refuses source distributions and artifacts absent from this lock.
"""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "deploy/media-worker/requirements.in"
OUTPUT = ROOT / "deploy/media-worker/requirements.lock"
HEADER = ("# Generated by python tools/lock_media_requirements.py; do not edit by hand.\n"
          "# Python 3.12+; installed with --only-binary=:all: --require-hashes.\n")


def main():
    subprocess.run([sys.executable, "-m", "uv", "pip", "compile", str(SOURCE),
                    "--universal", "--python-version", "3.12", "--generate-hashes",
                    "--no-header", "--no-annotate", "--quiet", "--output-file", str(OUTPUT)],
                   cwd=ROOT, check=True)
    content = OUTPUT.read_text(encoding="utf-8")
    OUTPUT.write_text(HEADER + content, encoding="utf-8", newline="\n")
    print("Wrote deploy/media-worker/requirements.lock:",
          sum("==" in line for line in content.splitlines()), "packages")


if __name__ == "__main__":
    main()
