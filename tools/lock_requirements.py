"""Write the hash locks that servers install from: every package pinned with its SHA-256 hashes.

    python tools/lock_requirements.py   # needs uv (pip install uv) and network access to PyPI

deploy/requirements.lock: pyproject's dependencies under deploy/constraints.txt, resolved for every
platform (uv --universal) with Python 3.11 or newer, each version with the hashes of all its files.
deploy/build.lock: setuptools, which builds this project and the packages published only as source
(pyaes), installed first so that no build fetches an unhashed package.

With pip install --require-hashes a file replaced on PyPI or a mirror is refused even when its version
number is the same. Regenerate both locks when the constraints change.

deploy/audit.lock, site.lock, browser.lock and mcp.lock separate CI tool scopes;
browser/mcp include the project's dependencies under constraints-mcp.txt. Install
build.lock before either project scope, with --no-build-isolation for all later
installs. audit/site support --only-binary=:all:. Local source is installed with
--no-deps --no-build-isolation after its dependencies, not resolved from PyPI.
Use --only audit site browser mcp to preserve the existing runtime/build locks.
Use --check in PR CI to reject changed inputs before running package installers.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEPLOY = ROOT / "deploy"
BUILD = "setuptools>=84.1.0"
CI_PINS = {"audit": ["pip-audit==2.10.1", "ruff==0.17.3"],
           "site": ["playwright==1.64.1", "markdown==3.11.2"],
           "browser": ["playwright==1.64.1", "ruff==0.17.3"], "mcp": []}
HEADER = ("# Generated by python tools/lock_requirements.py; do not edit by hand.\n"
          "# Installed with pip install --require-hashes (see INSTALL in tgwitness/cloud.py and deploy/Dockerfile).\n")


def compile_lock(sources, output, *options, header=HEADER):
    subprocess.run([sys.executable, "-m", "uv", "pip", "compile", *sources, "--generate-hashes", "--universal",
                    "--python-version", "3.11", "--no-header", "--no-annotate", "--quiet", "--output-file", str(output),
                    *options], cwd=ROOT, check=True)
    output.write_text(header + output.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")


def ci_header(kind):
    files = ("pyproject.toml", "deploy/constraints.txt", "deploy/constraints-mcp.txt") if kind in ("browser", "mcp") else ()
    extras = ["mcp"] if kind == "mcp" else ["dev", "mcp"] if kind == "browser" else []
    recipe = {"kind": kind, "python": "3.11", "pins": CI_PINS[kind],
              "extras": extras,
              "files": {name: (ROOT / name).read_text(encoding="utf-8") for name in files}}
    digest = hashlib.sha256(json.dumps(recipe, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return ("# Generated by python tools/lock_requirements.py; do not edit by hand.\n"
            "# Install with --require-hashes; install the local project separately with --no-deps.\n"
            "# Inputs-SHA256: " + digest + "\n")


def check_ci_locks():
    """Detect changed optional-lock inputs without installing or resolving packages."""
    stale = [kind for kind in CI_PINS if not (DEPLOY / (kind + ".lock")).is_file()
             or not (DEPLOY / (kind + ".lock")).read_text(encoding="utf-8").startswith(ci_header(kind))]
    if stale:
        raise SystemExit("Stale CI locks: " + ", ".join(stale)
                         + ". Run python tools/lock_requirements.py --only " + " ".join(stale))
    print("CI hash-lock inputs match:", ", ".join(CI_PINS) + ".")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", nargs="+", choices=("runtime", "build", *CI_PINS),
                        help="Regenerate only the selected lock scopes")
    parser.add_argument("--check", action="store_true", help="Check CI lock input digests without network access")
    args = parser.parse_args()
    if args.check:
        check_ci_locks()
        return
    selected = set(args.only or ("runtime", "build", *CI_PINS))
    written = []
    if "runtime" in selected:
        compile_lock(["pyproject.toml"], DEPLOY / "requirements.lock", "--constraints", "deploy/constraints.txt")
        written.append("requirements.lock")
    with tempfile.TemporaryDirectory(dir=ROOT / "build" if (ROOT / "build").is_dir() else None) as folder:
        if "build" in selected:
            source = Path(folder) / "build.in"
            source.write_text(BUILD + "\n", encoding="utf-8")
            compile_lock([str(source)], DEPLOY / "build.lock")
            written.append("build.lock")
        for kind in CI_PINS:
            if kind not in selected:
                continue
            source = Path(folder) / (kind + ".in")
            source.write_text("\n".join(CI_PINS[kind]) + "\n", encoding="utf-8")
            options = ()
            sources = [str(source)]
            if kind in ("browser", "mcp"):
                sources.append("pyproject.toml")
                options = ("--extra", "mcp", "--constraints", "deploy/constraints-mcp.txt")
                if kind == "browser":
                    options += ("--extra", "dev")
            compile_lock(sources, DEPLOY / (kind + ".lock"), *options, header=ci_header(kind))
            written.append(kind + ".lock")
    for name in written:
        text = (DEPLOY / name).read_text(encoding="utf-8")
        print("wrote deploy/" + name + ":", sum(1 for line in text.splitlines() if "==" in line), "packages")


if __name__ == "__main__":
    main()
