"""Render translated notice documents from the website catalogues, without network access."""
import argparse
import html
from pathlib import Path
import posixpath
import re
from urllib.parse import unquote, urlsplit, urlunsplit

if __package__:
    from . import site_i18n, site_wiki
    from .site_content import REFERENCE
else:
    import site_i18n
    import site_wiki
    from site_content import REFERENCE

ROOT = Path(__file__).resolve().parents[1]
SLUGS = ('license', 'notice')


def outputs(root=ROOT):
    root = Path(root).resolve()
    sources = {slug: REFERENCE[slug][3] for slug in SLUGS}
    planned = {f'docs/{lang}/{Path(source).name}' for lang in site_i18n.LANGUAGES if lang != 'en'
               for source in sources.values()}
    result = {}
    for lang, (_, code, direction, _) in site_i18n.LANGUAGES.items():
        if lang == 'en':
            continue
        data = site_i18n.load(root, lang)
        for slug, source in sources.items():
            title, body = site_wiki.split_title((root / source).read_text(encoding='utf-8'))
            if title not in data['strings']:
                raise ValueError(f'Missing translated notice title: {lang}/{slug}')
            markup, blocks = site_wiki.markup(body)
            if blocks:
                raise ValueError('Notice documents must not contain untranslated code or diagram blocks')
            translated, missing = site_i18n.localize(markup, data)
            if missing:
                raise ValueError(f'Incomplete notice translation: {lang}/{slug} ({missing} blocks)')
            destination = f'docs/{lang}/{Path(source).name}'

            def link(match):
                url = urlsplit(html.unescape(match[1]))
                if url.scheme or url.netloc or not url.path:
                    return match[0]
                target = (root / source).parent / unquote(url.path)
                target = target.resolve().relative_to(root).as_posix()
                localized = f'docs/{lang}/{Path(target).name}'
                if target in ('README.md', 'docs/README.md'):
                    target = f'docs/{lang}/README.md'
                elif target.startswith('docs/') and (localized in planned or (root / localized).is_file()):
                    target = localized
                if target not in planned and not (root / target).is_file():
                    raise ValueError(f'Unknown notice link: {source}: {url.path}')
                relative = posixpath.relpath(target, posixpath.dirname(destination))
                return 'href="' + html.escape(urlunsplit(('', '', relative, url.query, url.fragment)), quote=True) + '"'

            translated = re.sub(r'\bhref="([^"]+)"', link, translated)
            result[destination] = (
                '<!-- Generated by tools/sync_notice_translations.py from website/i18n. -->\n'
                f'<div lang="{code}" dir="{direction}">\n'
                f'<h1>{html.escape(data["strings"][title])}</h1>\n'
                f'<p><a href="../{Path(source).name}" lang="en">English</a></p>\n\n'
                + translated + '\n</div>\n'
            )
        readme = f'docs/{lang}/README.md'
        content = (root / readme).read_text(encoding='utf-8')
        title = site_wiki.split_title((root / sources['license']).read_text(encoding='utf-8'))[0]
        label = data['strings'][title]
        content, count = re.subn(r'\[[^\]\n]+\]\((?:\.\./)?TAYLOR-WESSING-EXCLUSION\.md\)',
                                lambda _: f'[{label}](TAYLOR-WESSING-EXCLUSION.md)', content)
        if count != 1:
            raise ValueError(f'Expected one notice link in {readme}, found {count}')
        result[readme] = content
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if path.is_file() and path.read_text(encoding='utf-8') == text:
            continue
        if args.check:
            stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    if stale:
        parser.exit(1, 'Notice translations need regeneration: ' + ', '.join(stale) + '\n')
    print('Notice translations are consistent.' if args.check else 'Updated translated notices and README links.')


if __name__ == '__main__':
    main()
