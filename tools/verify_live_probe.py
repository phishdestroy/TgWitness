"""Verify one canary message, its edit and deletion in independently pinned account exports. Sends nothing."""
import argparse
import json
from pathlib import Path
import re
import secrets
import sys
import zipfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tgwitness.verify import parse_time, verify_bundle


def check_probe(nonce, bundles):
    if not re.fullmatch(r"TGW-PROBE\.[0-9a-f]{24}", nonce):
        raise ValueError("Use a nonce generated by --new")
    results, keys = [], set()
    for label, path, pin in bundles:
        if not re.fullmatch(r"[0-9a-f]{64}", pin):
            raise ValueError("Each export requires its independently retained fingerprint")
        verified = verify_bundle(path, pin)
        if pin in keys:
            raise ValueError("Two exports belong to the same workspace key")
        keys.add(pin)
        first, edited, deleted, starts = None, None, None, 0
        with zipfile.ZipFile(path) as archive, archive.open("events.jsonl") as stream:
            for line in stream:
                event = json.loads(line)
                text = str(event["payload"].get("text", ""))
                if event["kind"] == "message.new" and nonce in text:
                    starts += 1
                    if first is None:
                        first = event
                if first is None or (event["chat_id"], event["message_id"]) != (first["chat_id"], first["message_id"]):
                    continue
                if (edited is None and event["kind"] == "message.edited" and event["seq"] > first["seq"]
                        and nonce in text and event["payload"].get("text") != first["payload"].get("text")):
                    edited = event
                if deleted is None and edited and event["kind"] == "message.deleted" and event["seq"] > edited["seq"]:
                    deleted = event
        if starts != 1 or first["chat_id"] is None or first["message_id"] is None:
            raise ValueError(label + ": expected exactly one live new-message observation for this nonce")
        if edited is None:
            raise ValueError(label + ": the changed version was not captured")
        if deleted is None:
            raise ValueError(label + ": no later deletion notice for this message")
        result = {"label": label, "collector_fingerprint": pin, "verified_events": verified["events"],
                  "new_seq": first["seq"], "edit_seq": edited["seq"], "delete_seq": deleted["seq"],
                  "first_observed_at": first["observed_at"], "last_observed_at": deleted["observed_at"]}
        if first.get("source_at"):
            result["reported_capture_delay_seconds"] = (parse_time(first["observed_at"]) - parse_time(first["source_at"])).total_seconds()
        results.append(result)
    if not results:
        raise ValueError("Provide at least one export")
    return {"passed": True, "nonce": nonce, "distinct_workspaces": len(results), "workspaces": results,
            "scope": "one controlled new/edit/delete sequence; not proof of complete collection"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--new", action="store_true", help="Generate a nonce locally; does not send a message")
    parser.add_argument("--nonce")
    parser.add_argument("--workspace", nargs=3, action="append", metavar=("LABEL", "EVIDENCE_ZIP", "FINGERPRINT"))
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    if args.new:
        print("TGW-PROBE." + secrets.token_hex(12))
        return
    try:
        result = check_probe(args.nonce or "", args.workspace or [])
    except (ValueError, OSError, KeyError) as exc:
        parser.exit(1, "PROBE FAILED: " + str(exc) + "\n")
    text = json.dumps(result, indent=2, ensure_ascii=False) + "\n"
    if args.out:
        args.out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
